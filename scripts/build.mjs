import fs from 'node:fs';
const root=new URL('../',import.meta.url),dictionaries=JSON.parse(fs.readFileSync(new URL('plugin/ru.json',root),'utf8'));
const source=`// Generated by scripts/build.mjs from plugin/ru.json.\nwindow.__ModuleLoader__.load({
 id: 'dsh-locale-ru-local',
 factory: () => {
  const dictionaries = ${JSON.stringify(dictionaries)};
  return {
   inject: ['locale'],
   apply(ctx) {
    for (const [ns, dictionary] of Object.entries(dictionaries)) {
     ctx.effect(() => ctx.locale.register(ns, 'ru', dictionary), 'ru: ' + ns);
    }
    ctx.effect(() => ctx.locale.addLanguage({id: 'ru', label: 'Русский', fallback: 'en'}), 'ru: language');
   }
  };
 }
});\n`;
fs.writeFileSync(new URL('plugin/lib/client.js',root),source);
console.log(`Built ${Object.keys(dictionaries).length} namespaces, ${Object.values(dictionaries).reduce((sum,d)=>sum+Object.keys(d).length,0)} strings`);
